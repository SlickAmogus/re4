#!/usr/bin/env python3
"""Writes xbox/units.mk and xbox/port/os/module_list.inc (xbox/docs/07-COMPILER.md).

    python3 xbox/tools/gen_units.py

DOL side: every unit of src/game except the debug-only units (DEBUG_UNITS), the SN newlib pieces
(*.c: pdclib/libc++ provide them) and the two whole-asm units replaced by xbox/port (CT-02); plus the
SDK C matrix code and fdlibm from src/lib.

Modules: the REL modules of config/G4BE08/config.yml with the unit lists of config/G4BE08/modules.py
(a module without an entry is the single unit <mod>/<mod>.cpp). Shared sources (src/wep/pl_handgun.cpp,
src/st/em_wrap.cpp, st1/st1.cpp ...) are compiled once per module that linked them, into
build/mod/<mod>/. The debug-tool modules (Tools, t_*) are skipped. After compiling, every module's
objects go through tools/isolate_modules.py, which prefixes the module's defined symbols so 100+
formerly separate link units coexist in one image; the module table (module_list.inc) gives the
runtime the renamed _prolog/_epilog per REL module id.
"""
import importlib.util
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'src')
CFG = os.path.join(ROOT, 'config', 'G4BE08')
OUT_MK = os.path.join(ROOT, 'xbox', 'units.mk')
OUT_INC = os.path.join(ROOT, 'xbox', 'port', 'os', 'module_list.inc')

# The debug units of src/game (db_log, dbmodule, db_menu, t_* ...) stay in: the game calls into them
# everywhere (pLog->err, Draw_*, DbMenuExec); pG->debug_mode = 0 keeps them inert at runtime.
DEBUG_UNITS = {
    'exception',            # PowerPC exception handler with register dumps; not installed on Xbox
    'yz2asm', 'memset_2',   # whole-function asm bodies, replaced by xbox/port C versions (CT-02)
}
DEBUG_MODULES = re.compile(r'^(Tools|t_\w+)$')

LIB_UNITS = [
    'mtx.c', 'mtxvec.c', 'mtx44.c', 'mtx44vec.c', 'vec.c', 'quat.c',
    'OSAlloc.c', 'OSStopwatch.c', 'OSTime.c',
    # The game's fdlibm (sf_sin, sf_cos, ef_acos, ef_sqrt, sf_fabs ...) duplicates pdclib's libm; the
    # platform versions are used. Revisit if a float-exactness issue is ever traced to libm.
]


def load_modules():
    spec = importlib.util.spec_from_file_location('re4_modules', os.path.join(CFG, 'modules.py'))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    names = re.findall(r'^\s+name:\s*(\S+)\s*$', open(os.path.join(CFG, 'config.yml')).read(), re.M)
    out = []
    for name in names:
        if DEBUG_MODULES.match(name):
            continue
        units = []
        for u in m.UNITS.get(name, [(f'{name}/{name}.cpp', None)]):
            src = u[2] if len(u) > 2 and u[2] else u[0]
            obj = os.path.splitext(u[0])[0]          # unit name, unique inside the module
            units.append((src, obj))
        rel = json.load(open(os.path.join(CFG, 'modules', name, 'rel.json')))
        out.append((name, rel['module_id'], units))
    return out


def main():
    lines = ['# Generated by xbox/tools/gen_units.py. Edit the generator, not this file.', '', 'GAME_UNITS :=']
    for name in sorted(os.listdir(os.path.join(SRC, 'game'))):
        stem, ext = os.path.splitext(name)
        if ext == '.cpp' and stem not in DEBUG_UNITS:
            lines.append(f'GAME_UNITS += src/game/{name}')
    lines += ['', 'LIB_UNITS := ' + ' '.join(f'src/lib/{u}' for u in LIB_UNITS if os.path.exists(os.path.join(SRC, 'lib', u))), '']

    mods = load_modules()
    lines.append('# REL modules: MODULE_<name> = list of <source under src/>:<object name under build/mod/<name>/>')
    lines.append('MODULE_NAMES := ' + ' '.join(n for n, _, _ in mods))
    for name, mid, units in mods:
        lines.append(f'MODULE_{name} := ' + ' '.join(f'{src}:{obj}' for src, obj in units))
    lines.append('')
    with open(OUT_MK, 'w', newline='\n') as f:
        f.write('\n'.join(lines))

    inc = ['/* Generated by xbox/tools/gen_units.py: RE4_MODULE(name, REL module id).',
           ' * isolate_modules.py renames each module\'s _prolog/_epilog/_unresolved to',
           ' * re4mod_<name>_prolog/_epilog/_unresolved. */']
    for name, mid, _ in mods:
        inc.append(f'RE4_MODULE({name}, {mid})')
    with open(OUT_INC, 'w', newline='\n') as f:
        f.write('\n'.join(inc) + '\n')
    print(f'{len(mods)} modules, {sum(len(u) for _, _, u in mods)} module units -> {OUT_MK}, {OUT_INC}')


if __name__ == '__main__':
    main()
