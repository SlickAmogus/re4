#!/usr/bin/env python3
"""Writes xbox/units.mk: the explicit list of game units the port compiles (xbox/docs/07-COMPILER.md).

    python3 xbox/tools/gen_units.py            # rewrites xbox/units.mk

Excluded: the debug editors (src/Tools, src/tools, src/t_*), the debug-only units of src/game listed in
DEBUG_UNITS, and src/lib except the C matrix/vector/quaternion code, fdlibm and OSAlloc (the CRI stack is
added by CT-07 behind RE4_MOVIES). Module directories get per-directory -D flags that rename
_prolog/_epilog/_unresolved so all 100+ formerly dynamically loaded modules link into one image.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'src')
OUT = os.path.join(ROOT, 'xbox', 'units.mk')

# src/game units that only exist for the debug build. Kept out until CT-03 proves which are needed.
DEBUG_UNITS = {
    'db_cam', 'db_log', 'db_menu', 'db_work', 'dbmodule', 'debug', 'exception',
    't_bugcheck', 't_flag', 't_log', 't_option', 't_page', 't_prim', 't_sc_shot', 't_util',
    'yz2asm', 'memset_2',   # whole-function asm bodies, replaced by xbox/port C versions (CT-02)
}

LIB_UNITS = [
    'mtx.c', 'mtxvec.c', 'mtx44.c', 'vec.c', 'quat.c',
    'OSAlloc.c',
    'sf_sin.cpp', 'sf_cos.cpp', 'kf_sin.cpp', 'kf_cos.cpp', 'ef_rem_pio2.cpp', 'kf_rem_pio2.cpp',
    'sf_scalbn.cpp', 'sf_floor.cpp', 'sf_fabs.cpp', 'ef_acos.cpp', 'ef_sqrt.cpp',
]

MODULE_DIR = re.compile(r'^(Sscrn|em[0-9a-f]{2}|pl[0-9a-f]{2}|wep[0-9]{2}|st[1-4])$')


def units_in(d):
    out = []
    for name in sorted(os.listdir(d)):
        if name.endswith(('.cpp', '.c')):
            out.append(name)
    return out


def main():
    lines = ['# Generated by xbox/tools/gen_units.py. Edit the generator, not this file.', '',
             'GAME_UNITS :=']
    for name in units_in(os.path.join(SRC, 'game')):
        stem = os.path.splitext(name)[0]
        if stem in DEBUG_UNITS:
            continue
        lines.append(f'GAME_UNITS += src/game/{name}')
    lines += ['', '# shared stage helpers (src/st: cEmWrap, cSceObj) link with the DOL side']
    if os.path.isdir(os.path.join(SRC, 'st')):
        for name in units_in(os.path.join(SRC, 'st')):
            lines.append(f'GAME_UNITS += src/st/{name}')
    lines += ['', '# the formerly dynamically loaded modules; MODULE_<name>_UNITS and a define per module']
    lines.append('MODULE_NAMES :=')
    for d in sorted(os.listdir(SRC)):
        if not MODULE_DIR.match(d) or d == 'st':
            continue
        if d == 'wep':
            continue
        units = units_in(os.path.join(SRC, d))
        if not units:
            continue
        lines.append(f'MODULE_NAMES += {d}')
        lines.append(f'MODULE_{d}_UNITS := ' + ' '.join(f'src/{d}/{u}' for u in units))
    # src/wep holds the player-side weapon routines shared by the wepNN modules
    if os.path.isdir(os.path.join(SRC, 'wep')):
        lines += ['', 'GAME_UNITS += ' + ' '.join(f'src/wep/{u}' for u in units_in(os.path.join(SRC, 'wep')))]
    lines += ['', '# SDK C code and libm the port reuses']
    lines.append('LIB_UNITS := ' + ' '.join(f'src/lib/{u}' for u in LIB_UNITS if os.path.exists(os.path.join(SRC, 'lib', u))))
    lines.append('')
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines))
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
