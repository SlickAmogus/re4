#!/usr/bin/env python3
"""Regenerates xbox/port/gx/gx_stubs.cpp from the GX prototypes in include/gx.h (the game's own
declarations, plain-int enums). Each entry point logs "unimplemented" once. CT-08 replaces the stubs
with the state machine; keep this script so the list can be re-derived after upstream changes."""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = open(os.path.join(ROOT, 'include', 'gx.h')).read()
protos = [p.strip() for p in re.findall(r'^(?:void|u32|int|f32|u8|s32)\s*\*?\s*(?:__)?GX\w+\s*\([^;]*\)\s*;', src, re.M)]
seen, order = {}, []
for p in protos:
    name = re.search(r'(__GX\w+|GX\w+)\s*\(', p).group(1)
    if name not in seen:
        seen[name] = p
        order.append(name)
out = ['// Generated by xbox/tools/gen_gx_stubs.py from include/gx.h: every GX entry point the game declares,',
       '// as logging stubs. Replace each with the real state-machine implementation (CT-08).',
       '#include "re4port/re4_xbox.h"', '#include "re4port/gx_shim.h"', '#include "gx.h"', '',
       'static void gx_unimpl(const char* fn) { re4_log_once(fn, "GX: unimplemented %s\\n", fn); }', '']
for n in order:
    p = seen[n]
    ret = re.match(r'(\w+\s*\*?)\s*(?:__)?GX', p).group(1).strip()
    body = 'gx_unimpl("%s");' % n
    if ret != 'void':
        body += ' return 0;'
    out.append('extern "C" ' + p[:-1] + '\n{\n    ' + body + '\n}\n')
dst = os.path.join(ROOT, 'xbox', 'port', 'gx', 'gx_stubs.cpp')
open(dst, 'w').write('\n'.join(out))
print(len(order), 'GX stubs ->', dst)
