#!/usr/bin/env python3
"""gen_modseg.py — per-module section control for the REL lifecycle (cloud-tasks/CT-12, 07-COMPILER.md).

    python3 xbox/tools/gen_modseg.py <module> <out dir>

Writes <out dir>/<module>.seg.h, force-included into every unit of the module, and
<out dir>/<module>.seg.cpp, one extra object of the module. With clang's MSVC-mode pragmas the
module's initialised data, zero data and dynamic-initialiser pointers go to `$`-grouped sections

    .data$re4m_<mod>$m   .bss$re4m_<mod>$m   .re4ct$re4m_<mod>$m

which lld sorts by name inside .data / .bss / .re4ct, so each module is one contiguous range bracketed
by the `$a` / `$z` markers defined in the .seg.cpp. The dynamic initialisers no longer sit in
.CRT$XCU, so the CRT does not run them at boot: xbox/port/os/module_table.cpp runs them when the game
links the module (OSLink), after restoring .data from a boot-time snapshot and zeroing .bss, which is
what reading a fresh REL from disc did on the GameCube. The marker symbols are renamed by
isolate_modules.py to _re4m_<mod>_re4seg_* like any other module symbol.
"""
import os
import sys

HDR = '''/* Generated by xbox/tools/gen_modseg.py for module {m}: per-module data/bss/initialiser sections. */
#pragma data_seg(".data$re4m_{m}$m")
#pragma bss_seg(".bss$re4m_{m}$m")
#pragma init_seg(".re4ct$re4m_{m}$m")
'''

SRC = '''/* Generated by xbox/tools/gen_modseg.py for module {m}: range markers of its sections. */
#pragma section(".re4ct$re4m_{m}$a", read)
#pragma section(".re4ct$re4m_{m}$z", read)
extern "C" {{
__declspec(allocate(".re4ct$re4m_{m}$a")) void (*re4seg_ct_begin)(void) = 0;
__declspec(allocate(".re4ct$re4m_{m}$z")) void (*re4seg_ct_end)(void) = 0;
#pragma data_seg(".data$re4m_{m}$a")
__attribute__((aligned(32))) char re4seg_data_begin = 1;
#pragma data_seg(".data$re4m_{m}$z")
char re4seg_data_end = 1;
#pragma data_seg()
#pragma bss_seg(".bss$re4m_{m}$a")
__attribute__((aligned(32))) char re4seg_bss_begin;
#pragma bss_seg(".bss$re4m_{m}$z")
char re4seg_bss_end;
#pragma bss_seg()
}}
'''


def main():
    m, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    for name, text in ((f'{m}.seg.h', HDR), (f'{m}.seg.cpp', SRC)):
        p = os.path.join(out, name)
        body = text.format(m=m)
        if not os.path.exists(p) or open(p).read() != body:
            with open(p, 'w', newline='\n') as f:
                f.write(body)


if __name__ == '__main__':
    main()
